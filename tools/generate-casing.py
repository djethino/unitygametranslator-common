#!/usr/bin/env python3
"""Writes the first-letter case tables of the socle, from the Unicode Character Database.

  src/UnityGameTranslator.Common/Casing.Tables.g.cs   what C# reads (Casing.UpperFirst / LowerFirst)
  corpus/data/first-letter.json                        what a port in another language reads (the site's editor)

The definition is in spec/translation-file/casing.md. In short: the FIRST code point of a text only, the
language-independent mapping only — UnicodeData's simple one, with SpecialCasing's UNCONDITIONAL multi-letter
ones laid over it (« ß » → « Ss »); the capital is Unicode's TITLECASE (« ǆ » → « ǅ »), else the uppercase.

🔴 The Unicode version is the PROJECT's, not this script's: it must equal the one the mod pins in its own
generators (UnityGameTranslator/tools/generate-shaping-tables.py, generate-indic-tables.py,
generate-bidi-trie, generate-case-tables.py) — moved to in all of them at once, never "latest". Inputs are the
two files of that version: given in a folder, or downloaded when the folder is absent (never at build time:
the build reads the committed tables). Both files' SHA-256 are written in the generated header and in the JSON,
so a table made from other bytes is visible; `--check` regenerates in memory and says whether the committed
tables are the ones these sources give (exit code 1 when not).

⚠ Never from Python's unicodedata, which is the Unicode of the Python that happens to run this.

Usage:  python tools/generate-casing.py [--check] [dir-with-UnicodeData.txt-and-SpecialCasing.txt]
"""
import hashlib
import io
import json
import os
import sys
import urllib.request

VERSION = "18.0.0"
UCD = "https://www.unicode.org/Public/%s/ucd/" % VERSION
HERE = os.path.dirname(os.path.abspath(__file__))
OUT_CS = os.path.join(HERE, "..", "src", "UnityGameTranslator.Common", "Casing.Tables.g.cs")
OUT_JSON = os.path.join(HERE, "..", "corpus", "data", "first-letter.json")


def load(name, src_dir):
    if src_dir:
        path = os.path.join(src_dir, name)
        if os.path.exists(path):
            return io.open(path, "rb").read()
    with urllib.request.urlopen(UCD + name) as r:
        return r.read()


def code_points(field):
    return [int(x, 16) for x in field.split()] if field else []


def text_of(cps):
    return "".join(chr(c) for c in cps)


def build(data_bytes, special_bytes):
    data = data_bytes.decode("utf-8")
    special = special_bytes.decode("utf-8")
    upper, lower, title = {}, {}, {}
    for line in data.splitlines():
        f = line.split(";")
        if len(f) < 15:
            continue
        cp = int(f[0], 16)
        if f[1].endswith(", First>"):   # a block of letters with no case
            continue
        if f[12]: upper[cp] = chr(int(f[12], 16))
        if f[13]: lower[cp] = chr(int(f[13], 16))
        if f[14]: title[cp] = chr(int(f[14], 16))

    # SpecialCasing: code; lower; title; upper; (condition;) # comment — unconditional lines only.
    for line in special.splitlines():
        body = line.split("#")[0].strip()
        if not body:
            continue
        f = [x.strip() for x in body.split(";")]
        if len(f) < 4 or (len(f) > 4 and f[4]):
            continue
        cp = int(f[0], 16)
        lo, ti, up = code_points(f[1]), code_points(f[2]), code_points(f[3])
        if lo: lower[cp] = text_of(lo)
        if ti: title[cp] = text_of(ti)
        if up: upper[cp] = text_of(up)

    capital = {cp: title.get(cp, upper.get(cp)) for cp in set(upper) | set(title)}
    capital = {cp: v for cp, v in capital.items() if v != chr(cp)}
    small = {cp: v for cp, v in lower.items() if v != chr(cp)}
    return capital, small


def escape(s):
    return "".join("\\u%04X" % ord(c) if ord(c) < 0x10000 else "\\U%08X" % ord(c) for c in s)


def render_cs(capital, small, sources):
    out = []
    w = out.append
    w("// <auto-generated>")
    w("// Generated by tools/generate-casing.py from the Unicode Character Database %s" % VERSION)
    w("// (UnicodeData, SpecialCasing — unconditional mappings only). Do not edit: change the generator.")
    for name in sorted(sources):
        w("// %s-sha256: %s" % (name, sources[name]))
    w("// </auto-generated>")
    w("namespace UnityGameTranslator.Common")
    w("{")
    w("    public static partial class Casing")
    w("    {")
    w('        /// <summary>The Unicode version of the tables: the project\'s one, equal to the mod\'s.</summary>')
    w('        public const string UnicodeVersion = "%s";' % VERSION)
    for name, table in (("Capital", capital), ("Small", small)):
        keys = sorted(table)
        w("")
        w("        private static readonly int[] %sKeys = {" % name)
        for i in range(0, len(keys), 12):
            w("            " + ", ".join("0x%X" % k for k in keys[i:i + 12]) + ",")
        w("        };")
        w("        private static readonly string[] %sValues = {" % name)
        for i in range(0, len(keys), 6):
            w("            " + ", ".join('"%s"' % escape(table[k]) for k in keys[i:i + 6]) + ",")
        w("        };")
    w("    }")
    w("}")
    return "\n".join(out) + "\n"


def render_json(capital, small, sources):
    doc = {
        "unicode_version": VERSION,
        "note": "First-letter case, language-independent (spec/translation-file/casing.md). Generated by tools/generate-casing.py: do not edit. Keys are code points in upper-case hexadecimal.",
        "sources_sha256": sources,
        "capital": {"%X" % cp: capital[cp] for cp in sorted(capital)},
        "small": {"%X" % cp: small[cp] for cp in sorted(small)},
    }
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    src_dir = args[0] if args else None
    data = load("UnicodeData.txt", src_dir)
    special = load("SpecialCasing.txt", src_dir)
    sources = {"UnicodeData": hashlib.sha256(data).hexdigest(), "SpecialCasing": hashlib.sha256(special).hexdigest()}
    capital, small = build(data, special)
    cs, js = render_cs(capital, small, sources), render_json(capital, small, sources)

    if check:
        stale = []
        for path, text in ((OUT_CS, cs), (OUT_JSON, js)):
            have = io.open(path, "rb").read().decode("utf-8") if os.path.exists(path) else None
            if have != text:
                stale.append(os.path.normpath(path))
        if stale:
            print("STALE: " + ", ".join(stale) + " — run tools/generate-casing.py")
            sys.exit(1)
        print("up to date (Unicode %s, %d capitals, %d small letters)" % (VERSION, len(capital), len(small)))
        return

    os.makedirs(os.path.dirname(OUT_JSON), exist_ok=True)
    for path, text in ((OUT_CS, cs), (OUT_JSON, js)):
        with io.open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("wrote %d capitals, %d small letters (Unicode %s)" % (len(capital), len(small), VERSION))


if __name__ == "__main__":
    main()
