#!/usr/bin/env python3
"""Writes KeyChars.Tables.g.cs: the two character facts the shape of a text's KEY needs, from the Unicode Character
Database — the decimal digits (general category Nd) and the white space (White_Space), of the Basic Multilingual Plane.

Why only the Basic Multilingual Plane: the key is read UTF-16 unit by unit, exactly as the regular expression and
Trim() of the mod's runtime read it (a surrogate is no digit and no space to them), and a key already written in a
file must be found again. A digit outside the plane is not a number of the key; this is a FACT of the key, said in
spec/translation-file/key.md, not a defect to correct without a migration.

🔴 The Unicode version is the PROJECT's (the one the mod pins, moved to in all generators at once — never « latest »).
Both source files' SHA-256 are in the header; `--check` regenerates in memory and says whether the committed table is the
one these sources give. Measured on 2026-11-14 on .NET 8.0.34: `\\d` and char.IsWhiteSpace / Trim() are, over the whole
plane, exactly these two sets (370 digits, 25 spaces): the tables change nothing there, and stop the key depending on
the game's runtime.

Usage:  python tools/generate-key-chars.py [--check] [dir-with-UnicodeData.txt-and-PropList.txt]
"""
import hashlib
import io
import os
import sys
import urllib.request

# The project's one Unicode version, written ONCE in common/UNICODE_VERSION (read by every generator of common; the
# mod's own generators are to read it too). Never "latest": moved to here, then every table regenerated.
VERSION = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UNICODE_VERSION"), encoding="utf-8").read().strip()
UCD = "https://www.unicode.org/Public/%s/ucd/" % VERSION
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "UnityGameTranslator.Common", "KeyChars.Tables.g.cs")
PLANE = 0xFFFF


def load(name, src_dir):
    if src_dir:
        path = os.path.join(src_dir, name)
        if os.path.exists(path):
            return io.open(path, "rb").read()
    with urllib.request.urlopen(UCD + name) as r:
        return r.read()


def ranges_of(cps):
    out = []
    for cp in sorted(cps):
        if cp > PLANE or 0xD800 <= cp <= 0xDFFF:
            continue
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def digits(data):
    found = []
    first = None
    for line in data.decode("utf-8").splitlines():
        f = line.split(";")
        if len(f) < 3:
            continue
        cp = int(f[0], 16)
        if f[2] == "Nd":
            found.append(cp)
    return ranges_of(found)


def white_space(data):
    found = []
    for line in data.decode("utf-8").splitlines():
        body = line.split("#")[0].strip()
        if not body:
            continue
        rng, prop = [x.strip() for x in body.split(";")]
        if prop == "White_Space":
            a = rng.split("..")
            found.extend(range(int(a[0], 16), int(a[-1], 16) + 1))
    return ranges_of(found)


def render(unicode_data, prop_list):
    nd, ws = digits(unicode_data), white_space(prop_list)
    out = []
    w = out.append
    w("// <auto-generated>")
    w("// Generated by tools/generate-key-chars.py from the Unicode Character Database %s" % VERSION)
    w("// (UnicodeData.txt: general category Nd; PropList.txt: White_Space) — the Basic Multilingual Plane only.")
    w("// Do not edit: change the generator.")
    w("// UnicodeData-sha256: %s" % hashlib.sha256(unicode_data).hexdigest())
    w("// PropList-sha256: %s" % hashlib.sha256(prop_list).hexdigest())
    w("// </auto-generated>")
    w("namespace UnityGameTranslator.Common")
    w("{")
    w("    public static partial class KeyChars")
    w("    {")
    w('        /// <summary>The Unicode version of the tables: the project\'s one, equal to the mod\'s.</summary>')
    w('        public const string UnicodeVersion = "%s";' % VERSION)
    for name, rngs, doc in (("DigitRanges", nd, "Decimal digits (Nd) of the Basic Multilingual Plane"),
                            ("SpaceRanges", ws, "White_Space of the Basic Multilingual Plane")):
        w("")
        w("        /// <summary>%s — inclusive ranges, sorted, as (first, last) pairs.</summary>" % doc)
        w("        private static readonly int[] %s =" % name)
        w("        {")
        for i in range(0, len(rngs), 4):
            w("            " + ", ".join("0x%X, 0x%X" % (a, b) for a, b in rngs[i:i + 4]) + ",")
        w("        };")
    w("    }")
    w("}")
    return "\n".join(out) + "\n", sum(b - a + 1 for a, b in nd), sum(b - a + 1 for a, b in ws)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    src = args[0] if args else None
    text, n_digits, n_spaces = render(load("UnicodeData.txt", src), load("PropList.txt", src))
    if "--check" in sys.argv:
        have = io.open(OUT, "rb").read().decode("utf-8") if os.path.exists(OUT) else None
        if have != text:
            print("STALE: %s — run tools/generate-key-chars.py" % os.path.normpath(OUT))
            sys.exit(1)
        print("up to date (Unicode %s, %d digits, %d spaces)" % (VERSION, n_digits, n_spaces))
        return
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %d digits, %d spaces (Unicode %s)" % (n_digits, n_spaces, VERSION))


if __name__ == "__main__":
    main()
