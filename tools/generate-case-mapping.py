#!/usr/bin/env python3
"""Writes CaseMapping.Tables.g.cs: the SIMPLE UPPERCASE of every code point that has one, from the Unicode Character Database
— the fold a NAME is compared and sorted by (Names).

Why uppercase, and simple: the runtime's OrdinalIgnoreCase compares texts by their upper-case letters, one code point to one
code point. Folding to upper case keeps the ORDER it gave — « _ » sorts after « Z » and before « a » in capitals as it did —
so no file written in that order moves (a .ugtpack lists its references so). A lower-case fold would put « _ » before the
letters. « Simple » = UnicodeData.txt field 12, one code point to one: « ß » stays « ß » (its full upper case is two letters).

🔴 No bridge between ASCII and the rest: a code point that is not ASCII never folds to an ASCII one (« ı » U+0131 would give
« I », « ſ » U+017F « S »). It is what .NET already does (ToUpperInvariant('ı') is 'ı'), what the Turkish « i » needs, and
what Ascii says of the 26 letters.

🔴 The Unicode version is the PROJECT's (common/UNICODE_VERSION; never « latest »). The source's SHA-256 is in the header;
`--check` regenerates in memory and says whether the committed table is the one this source gives.

Usage:  python tools/generate-case-mapping.py [--check] [dir-with-UnicodeData.txt]
"""
import hashlib
import io
import os
import sys
import urllib.request

VERSION = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UNICODE_VERSION"), encoding="utf-8").read().strip()
UCD = "https://www.unicode.org/Public/%s/ucd/" % VERSION
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "UnityGameTranslator.Common", "CaseMapping.Tables.g.cs")


def load(name, src_dir):
    if src_dir:
        path = os.path.join(src_dir, name)
        if os.path.exists(path):
            return io.open(path, "rb").read()
    with urllib.request.urlopen(UCD + name) as r:
        return r.read()


def mapping(data):
    pairs = {}
    skipped = []
    for line in data.decode("utf-8").splitlines():
        f = line.split(";")
        if len(f) < 15 or not f[12]:
            continue
        cp, upper = int(f[0], 16), int(f[12], 16)
        if upper == cp:
            continue
        if (cp < 0x80) != (upper < 0x80):
            skipped.append((cp, upper))
            continue
        if (cp > 0xFFFF) != (upper > 0xFFFF):
            raise SystemExit('a capital in another plane than its small letter: Names.Fold keeps the length in UTF-16 units and relies on it: U+%04X' % cp)
        pairs[cp] = upper
    return pairs, skipped


def render(data):
    pairs, skipped = mapping(data)
    keys = sorted(pairs)
    out = []
    w = out.append
    w("// <auto-generated>")
    w("// Generated by tools/generate-case-mapping.py from the Unicode Character Database %s (UnicodeData.txt, simple upper case)" % VERSION)
    w("// Do not edit: change the generator.")
    w("// UnicodeData-sha256: %s" % hashlib.sha256(data).hexdigest())
    w("// Left out on purpose (a code point beyond ASCII never folds to ASCII): %s" % ", ".join("U+%04X -> U+%04X" % s for s in skipped))
    w("// </auto-generated>")
    w("namespace UnityGameTranslator.Common")
    w("{")
    w("    public static partial class Names")
    w("    {")
    w('        /// <summary>The Unicode version of the table: the project\'s one, equal to the mod\'s.</summary>')
    w('        public const string UnicodeVersion = "%s";' % VERSION)
    w("")
    w("        /// <summary>The code points that have a simple upper case other than themselves, sorted.</summary>")
    w("        private static readonly int[] Lower =")
    w("        {")
    for i in range(0, len(keys), 12):
        w("            " + ", ".join("0x%X" % k for k in keys[i:i + 12]) + ",")
    w("        };")
    w("")
    w("        /// <summary>Their upper case, in the same order.</summary>")
    w("        private static readonly int[] Upper =")
    w("        {")
    for i in range(0, len(keys), 12):
        w("            " + ", ".join("0x%X" % pairs[k] for k in keys[i:i + 12]) + ",")
    w("        };")
    w("    }")
    w("}")
    return "\n".join(out) + "\n", len(keys), skipped


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    data = load("UnicodeData.txt", args[0] if args else None)
    text, n, skipped = render(data)
    if "--check" in sys.argv:
        have = io.open(OUT, "rb").read().decode("utf-8") if os.path.exists(OUT) else None
        if have != text:
            print("STALE: %s — run tools/generate-case-mapping.py" % os.path.normpath(OUT))
            sys.exit(1)
        print("up to date (Unicode %s, %d mappings, %d left out)" % (VERSION, n, len(skipped)))
        return
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %d mappings (Unicode %s); left out: %s" % (n, VERSION, skipped))


if __name__ == "__main__":
    main()
