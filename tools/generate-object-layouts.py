#!/usr/bin/env python3
"""Writes ObjectLayouts.Tables.g.cs: the shape of some of Unity's classes in every Unity version.

The same source and the same reasoning as generate-font-layouts.py (read that one's header): a game's
data files carry no type tree in a release build, so an object of a class is read along the layout
the engine version gave it. Published per version by AssetRipper/Tpk (MIT) as a "type tree" tpk.

One source for every generated table: FontLayouts and ObjectLayouts are written from the SAME tpk
(its SHA-256 is in both headers), and it is changed for all of them at once, never for one class.

Classes taken: TextAsset (49), MonoBehaviour (114) and MonoScript (115) - the ones the reading of a
game's texts asks for - and Transform (4) and RectTransform (224), which give the scene tree. Another class is added to CLASSES when a step of the chain names it as read.

Usage:
    python generate-object-layouts.py --tpk lzma.tpk          # from a tpk on disk
    python generate-object-layouts.py --tpk lzma.tpk --check  # exit 1 when the table is not this tpk's
"""

import argparse
import hashlib
import importlib.util
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, "..", "src", "UnityGameTranslator.Common", "UnityFiles", "ObjectLayouts.Tables.g.cs")
CLASSES = [(4, "Transform"), (49, "TextAsset"), (114, "MonoBehaviour"), (115, "MonoScript"), (224, "RectTransform")]

_spec = importlib.util.spec_from_file_location("fonts", os.path.join(HERE, "generate-font-layouts.py"))
fonts = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(fonts)


def render(tpk, sha):
    newest, classes, common, nodes, strings = fonts.read_tpk(tpk)
    per_class = []
    for cid, name in CLASSES:
        if cid not in classes:
            sys.exit(f"no {name} class in this tpk")
        layouts, keys = [], []
        for v, release in classes[cid]:
            tree = tuple(fonts.flatten(nodes, strings, release, 0, [])) if release is not None else None
            index = -1
            if tree is not None:
                if tree not in layouts:
                    layouts.append(tree)
                index = layouts.index(tree)
            if keys and keys[-1][1] == index:
                continue   # same layout as the version before: one entry per change
            keys.append((v, index))
        per_class.append((cid, name, layouts, keys))

    out = io.StringIO()
    w = out.write
    w("// <auto-generated>\n")
    w("//   By common/tools/generate-object-layouts.py from AssetRipper/Tpk's type tree tpk (MIT),\n")
    w(f"//   SHA-256 {sha}. Do not edit: rerun the generator.\n")
    w("// </auto-generated>\n")
    w("namespace UnityGameTranslator.Common.UnityFiles\n{\n")
    w("    public static partial class ObjectLayouts\n    {\n")
    w("        /// <summary>SHA-256 of the tpk these tables were written from.</summary>\n")
    w(f"        public const string SourceSha256 = \"{sha}\";\n\n")
    w(f"        /// <summary>The newest Unity version the source knew: {fonts.version_text(newest)} - a newer one may have changed a class.</summary>\n")
    w(f"        internal const ulong NewestKnown = 0x{newest:016X};\n\n")
    w("        /// <summary>The classes this table holds, by Unity's class id.</summary>\n")
    w("        internal static readonly int[] Classes = { " + ", ".join(str(c) for c, *_ in per_class) + " };\n\n")
    w("        /// <summary>Per class: from which Unity version (UnityVersions.Key) each layout applies.</summary>\n")
    w("        private static readonly ulong[][] Since =\n        {\n")
    for cid, name, layouts, keys in per_class:
        w(f"            new ulong[] // {name}\n            {{\n")
        for v, _ in keys:
            w(f"                0x{v:016X}, // {fonts.version_text(v)}\n")
        w("            },\n")
    w("        };\n\n")
    w("        /// <summary>Per class: which layout each of the versions above gives; -1 = the class does not exist then.</summary>\n")
    w("        private static readonly int[][] LayoutAt =\n        {\n")
    for cid, name, layouts, keys in per_class:
        w("            new[] { " + ", ".join(str(i) for _, i in keys) + " }, // " + name + "\n")
    w("        };\n\n")
    w("        /// <summary>Per class: each distinct release layout, in node order (depth first).</summary>\n")
    w("        private static readonly TypeNode[][][] Layouts =\n        {\n")
    for cid, name, layouts, keys in per_class:
        w(f"            new TypeNode[][] // {name}\n            {{\n")
        for i, tree in enumerate(layouts):
            first = next(fonts.version_text(v) for v, j in keys if j == i)
            w(f"                new[] // since {first}\n                {{\n")
            for depth, type_name, field_name, byte_size, type_flags, meta_flags in tree:
                w(f"                    new TypeNode({depth}, {fonts.cs(type_name)}, {fonts.cs(field_name)}, {byte_size}, {type_flags}, 0x{meta_flags:X}),\n")
            w("                },\n")
        w("            },\n")
    w("        };\n    }\n}\n")
    return out.getvalue().replace("\r\n", "\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--tpk", required=True)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    sha = hashlib.sha256(open(a.tpk, "rb").read()).hexdigest()
    text = render(a.tpk, sha)
    current = open(TARGET, "rb").read().decode("utf-8") if os.path.exists(TARGET) else None
    if a.check:
        if current != text:
            # Exit 1: a layout changed or the source is another one - a game of that version would be read wrongly.
            print(f"{TARGET}: the layouts differ from this tpk's ({sha})")
            sys.exit(1)
        print("up to date")
        return
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "wb") as f:
        f.write(text.encode("utf-8"))
    print(f"written from {a.tpk} ({sha})" + ("" if current != text else " - unchanged"))


if __name__ == "__main__":
    main()
