#!/usr/bin/env python3
"""Writes UnicodeCategories.Tables.g.cs: the GENERAL CATEGORY (Lu, Ll, Nd, Mn, Zs …) of every code point, from the Unicode
Character Database, all planes.

What it is for: « is this a letter, a mark, a number » is asked of the library's texts (Placeholders.IsWordCharacter first, the
names of games later) and must not be answered by the runtime — .NET 8 does not know the 22 041 letters outside the plane
and the 27 inside it that Unicode 18 does, a game's Mono and IL2CPP know fewer still (measured 2026-11-14, see
analyse/smart-suivi-socle.md). Same source, same version, same answer in the Manager, in a game and in a test.

🔴 The Unicode version is the PROJECT's (common/UNICODE_VERSION, read below; never « latest »). The source file's SHA-256 is in
the header; `--check` regenerates in memory and says whether the committed table is the one this source gives.

Layout: the code points that carry a category other than Cn (unassigned), as sorted inclusive ranges with one category index
each; adjacent code points of the same category are one range. The « First » / « Last » lines of UnicodeData (CJK blocks,
Hangul, private use) are ranges already. Surrogates (Cs) are not code points of a text and are left out.

Usage:  python tools/generate-general-category.py [--check] [dir-with-UnicodeData.txt]
"""
import hashlib
import io
import os
import sys
import urllib.request

# The project's one Unicode version, written ONCE in common/UNICODE_VERSION (read by every generator of common; the
# mod's own generators are to read it too). Never "latest": moved to here, then every table regenerated.
VERSION = io.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UNICODE_VERSION"), encoding="utf-8").read().strip()
UCD = "https://www.unicode.org/Public/%s/ucd/" % VERSION
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "UnityGameTranslator.Common", "UnicodeCategories.Tables.g.cs")

# Index = the category's place in this list; Cn (unassigned) is the answer for every code point no range covers.
NAMES = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
         "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Co"]


def load(name, src_dir):
    if src_dir:
        path = os.path.join(src_dir, name)
        if os.path.exists(path):
            return io.open(path, "rb").read()
    with urllib.request.urlopen(UCD + name) as r:
        return r.read()


def ranges_of(data):
    cats = {}
    first = None
    for line in data.decode("utf-8").splitlines():
        f = line.split(";")
        if len(f) < 3:
            continue
        cp = int(f[0], 16)
        name, cat = f[1], f[2]
        if name.endswith(", First>"):
            first = cp
            continue
        span = range(first, cp + 1) if name.endswith(", Last>") else [cp]
        first = None
        if cat == "Cs":
            continue
        if cat not in NAMES:
            raise SystemExit("a category this generator does not know: " + cat)
        for c in span:
            cats[c] = NAMES.index(cat)
    out = []
    for cp in sorted(cats):
        if out and out[-1][1] == cp - 1 and out[-1][2] == cats[cp]:
            out[-1][1] = cp
        else:
            out.append([cp, cp, cats[cp]])
    return out, len(cats)


def render(data):
    ranges, assigned = ranges_of(data)
    out = []
    w = out.append
    w("// <auto-generated>")
    w("// Generated by tools/generate-general-category.py from the Unicode Character Database %s (UnicodeData.txt)" % VERSION)
    w("// Do not edit: change the generator.")
    w("// UnicodeData-sha256: %s" % hashlib.sha256(data).hexdigest())
    w("// </auto-generated>")
    w("namespace UnityGameTranslator.Common")
    w("{")
    w("    public static partial class UnicodeCategories")
    w("    {")
    w('        /// <summary>The Unicode version of the table: the project\'s one, equal to the mod\'s.</summary>')
    w('        public const string UnicodeVersion = "%s";' % VERSION)
    w("")
    w("        /// <summary>The category names, in the order <see cref=\"Kinds\"/> indexes.</summary>")
    w("        private static readonly string[] Names = { %s };" % ", ".join('"%s"' % n for n in NAMES))
    w("")
    w("        /// <summary>The first code point of each range, sorted.</summary>")
    w("        private static readonly int[] Firsts =")
    w("        {")
    for i in range(0, len(ranges), 8):
        w("            " + ", ".join("0x%X" % r[0] for r in ranges[i:i + 8]) + ",")
    w("        };")
    w("")
    w("        /// <summary>The last code point of each range.</summary>")
    w("        private static readonly int[] Lasts =")
    w("        {")
    for i in range(0, len(ranges), 8):
        w("            " + ", ".join("0x%X" % r[1] for r in ranges[i:i + 8]) + ",")
    w("        };")
    w("")
    w("        /// <summary>The category of each range: an index into the names.</summary>")
    w("        private static readonly byte[] Kinds =")
    w("        {")
    for i in range(0, len(ranges), 24):
        w("            " + ", ".join(str(r[2]) for r in ranges[i:i + 24]) + ",")
    w("        };")
    w("    }")
    w("}")
    return "\n".join(out) + "\n", len(ranges), assigned


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    data = load("UnicodeData.txt", args[0] if args else None)
    text, n_ranges, n_cp = render(data)
    if "--check" in sys.argv:
        have = io.open(OUT, "rb").read().decode("utf-8") if os.path.exists(OUT) else None
        if have != text:
            print("STALE: %s — run tools/generate-general-category.py" % os.path.normpath(OUT))
            sys.exit(1)
        print("up to date (Unicode %s, %d ranges, %d code points)" % (VERSION, n_ranges, n_cp))
        return
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %d ranges, %d code points (Unicode %s)" % (n_ranges, n_cp, VERSION))


if __name__ == "__main__":
    main()
